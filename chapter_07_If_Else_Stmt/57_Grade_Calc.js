//Student Grade Calculator
let marks = 79;
if (marks >= 90) {
    console.log("Your Grade is A");
} else if (marks >= 80) {
    console.log("Your Grade is B");
} else if (marks >= 70) {
    console.log("Your Grade is C");
} else if (marks >= 60) {
    console.log("Your Grade is D");
} else {
    console.log("You have failed");
}